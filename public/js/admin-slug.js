document.addEventListener('DOMContentLoaded', () => {
  const slugify = (value) => {
    return value
      .normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
  };

  document.querySelectorAll('[data-auto-slug-name]').forEach((nameInput) => {
    const slugInput = document.querySelector(nameInput.dataset.autoSlugName);
    if (!slugInput) return;

    let slugWasManual = false;

    slugInput.addEventListener('input', () => {
      const manualValue = slugInput.value;
      slugWasManual = manualValue !== '' && manualValue !== slugify(nameInput.value);
    });

    nameInput.addEventListener('input', () => {
      if (!slugWasManual && (!slugInput.value || slugInput.dataset.autoGenerated === 'true')) {
        slugInput.value = slugify(nameInput.value);
        slugInput.dataset.autoGenerated = 'true';
      }
    });

    if (!slugInput.value) {
      slugInput.dataset.autoGenerated = 'true';
      slugInput.value = slugify(nameInput.value);
    } else {
      slugInput.dataset.autoGenerated = 'false';
    }
  });
});
